import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outputPath = path.join(rootDir, 'shared', 'public-suffix-data.js');

const toSortedLines = values => Array.from(new Set(values)).sort((a, b) => (
    a.localeCompare(b)
));

const buildOutput = ({
    generatedAt,
    exactRules,
    wildcardRules,
    exceptionRules,
}) => `// Generated by scripts/update-public-suffix-data.mjs
// Source: ${PSL_URL}
// Generated at: ${generatedAt}
(function talonPublicSuffixDataScope() {
    if ( globalThis.TalonPublicSuffixData ) { return; }
    globalThis.TalonPublicSuffixData = Object.freeze({
        generatedAt: ${JSON.stringify(generatedAt)},
        exactRulesText: ${JSON.stringify(exactRules.join('\n'))},
        wildcardRulesText: ${JSON.stringify(wildcardRules.join('\n'))},
        exceptionRulesText: ${JSON.stringify(exceptionRules.join('\n'))},
    });
})();

void 0;
`;

const response = await fetch(PSL_URL, {
    headers: {
        'user-agent': 'Talon Defender PSL Updater',
    },
});
if ( response.ok === false ) {
    throw new Error(`Failed to download PSL: ${response.status} ${response.statusText}`);
}

const decoder = new TextDecoder('utf-8');
const raw = decoder.decode(await response.arrayBuffer());
const exactRules = [];
const wildcardRules = [];
const exceptionRules = [];

for ( const line of raw.split(/\r?\n/) ) {
    const trimmed = line.trim().toLowerCase();
    if ( trimmed === '' || trimmed.startsWith('//') ) { continue; }
    if ( trimmed.startsWith('!') ) {
        exceptionRules.push(trimmed.slice(1));
        continue;
    }
    if ( trimmed.startsWith('*.') ) {
        wildcardRules.push(trimmed.slice(2));
        continue;
    }
    exactRules.push(trimmed);
}

const generatedAt = new Date().toISOString();
await fs.writeFile(outputPath, buildOutput({
    generatedAt,
    exactRules: toSortedLines(exactRules),
    wildcardRules: toSortedLines(wildcardRules),
    exceptionRules: toSortedLines(exceptionRules),
}), 'utf8');

console.log(`Wrote ${outputPath}`);
