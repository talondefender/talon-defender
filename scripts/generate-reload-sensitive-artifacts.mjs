import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';

const rootDir = process.cwd();
const resourceRoots = [
  'js/scripting/scriptlet-token',
  'rulesets/scripting/scriptlet',
];
const manifestRelativePath = 'rulesets/reload-sensitive-artifacts.json';
const metadataRelativePath = 'js/reload-sensitive-artifact-meta.js';

const collectJavaScriptFiles = async (relativeDir, out = []) => {
  const absoluteDir = path.join(rootDir, relativeDir);
  const entries = await fs.readdir(absoluteDir, { withFileTypes: true });
  for (const entry of entries) {
    const childRelativePath = path.posix.join(
      relativeDir.replaceAll('\\', '/'),
      entry.name
    );
    if (entry.isDirectory()) {
      await collectJavaScriptFiles(childRelativePath, out);
      continue;
    }
    if (entry.isFile() && entry.name.endsWith('.js')) {
      out.push(childRelativePath);
    }
  }
  return out;
};

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const sha256JavaScript = bytes => sha256(Buffer.from(
  bytes.toString('utf8').replace(/\r\n?/g, '\n'),
  'utf8'
));

const files = [];
for (const relativeDir of resourceRoots) {
  await collectJavaScriptFiles(relativeDir, files);
}
files.sort();

const resources = {};
for (const relativePath of files) {
  const bytes = await fs.readFile(path.join(rootDir, relativePath));
  resources[`/${relativePath}`] = sha256JavaScript(bytes);
}

const fingerprint = sha256(Buffer.from(JSON.stringify(resources), 'utf8'));
const manifest = {
  version: 1,
  fingerprint,
  resources,
};
const metadata = `// Generated by scripts/generate-reload-sensitive-artifacts.mjs.\n` +
  `// Do not edit by hand.\n` +
  `export const RELOAD_SENSITIVE_ARTIFACT_MANIFEST_VERSION = 1;\n` +
  `export const RELOAD_SENSITIVE_ARTIFACT_MANIFEST_FINGERPRINT = '${fingerprint}';\n` +
  `export const RELOAD_SENSITIVE_ARTIFACT_MANIFEST_PATH = ` +
  `'/${manifestRelativePath.replaceAll('\\', '/')}';\n`;

await fs.writeFile(
  path.join(rootDir, manifestRelativePath),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8'
);
await fs.writeFile(
  path.join(rootDir, metadataRelativePath),
  metadata,
  'utf8'
);

console.log(
  `Wrote ${Object.keys(resources).length} reload-sensitive artifact hashes ` +
  `(${fingerprint}).`
);
